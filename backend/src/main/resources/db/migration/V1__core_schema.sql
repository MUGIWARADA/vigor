-- =============================================================================
-- Vigor — Phase 2 core schema
-- Domains: competitions, seasons, teams, players, season stats, matches,
--          player match minutes, match events, import sources.
--
-- Conventions (docs/DATA-MODEL.md):
--   * every table carries created_at / updated_at;
--   * provenance on every data row (six labels, CHECK-constrained);
--   * source_id → import_sources ties IMPORTED rows to their source;
--   * missing values are NULL — never zero-as-missing;
--   * foreign keys declare explicit ON DELETE behaviour.
-- =============================================================================

-- ----------------------------------------------------------------------------
-- Import sources: registry that imported records are tied to.
-- ----------------------------------------------------------------------------
CREATE TABLE import_sources (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(120) NOT NULL,
    version      VARCHAR(60)  NOT NULL,
    licence_note VARCHAR(500),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------------------
-- Competitions / seasons
-- ----------------------------------------------------------------------------
CREATE TABLE competitions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(120) NOT NULL,
    short_name   VARCHAR(24)  NOT NULL,
    provenance   VARCHAR(20)  NOT NULL,
    source_name  VARCHAR(120) NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_competitions_provenance
        CHECK (provenance IN ('DEMO', 'IMPORTED', 'CALCULATED', 'MODEL_ESTIMATE', 'MANUAL', 'VERIFIED'))
);

CREATE TABLE seasons (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competition_id BIGINT       NOT NULL REFERENCES competitions (id) ON DELETE RESTRICT,
    label          VARCHAR(40)  NOT NULL,
    start_date     DATE         NOT NULL,
    end_date       DATE         NOT NULL,
    provenance     VARCHAR(20)  NOT NULL,
    source_name    VARCHAR(120) NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_seasons_provenance
        CHECK (provenance IN ('DEMO', 'IMPORTED', 'CALCULATED', 'MODEL_ESTIMATE', 'MANUAL', 'VERIFIED')),
    CONSTRAINT ck_seasons_dates CHECK (end_date > start_date)
);

-- ----------------------------------------------------------------------------
-- Teams
-- ----------------------------------------------------------------------------
CREATE TABLE teams (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(120) NOT NULL,
    short_name     VARCHAR(12)  NOT NULL,
    city           VARCHAR(120) NOT NULL,
    style          VARCHAR(40)  NOT NULL,
    formation      VARCHAR(12)  NOT NULL,
    primary_colour VARCHAR(9)   NOT NULL,
    provenance     VARCHAR(20)  NOT NULL,
    source_name    VARCHAR(120) NOT NULL,
    source_id      BIGINT       REFERENCES import_sources (id) ON DELETE SET NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_teams_provenance
        CHECK (provenance IN ('DEMO', 'IMPORTED', 'CALCULATED', 'MODEL_ESTIMATE', 'MANUAL', 'VERIFIED')),
    CONSTRAINT ck_teams_style
        CHECK (style IN ('Possession-oriented', 'Direct', 'Counterattacking', 'High-pressing')),
    CONSTRAINT uq_teams_short_name UNIQUE (short_name)
);

-- ----------------------------------------------------------------------------
-- Players + season aggregate statistics
-- ----------------------------------------------------------------------------
CREATE TABLE players (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id             BIGINT       NOT NULL REFERENCES teams (id) ON DELETE RESTRICT,
    full_name           VARCHAR(120) NOT NULL,
    position            VARCHAR(4)   NOT NULL,
    secondary_position  VARCHAR(4),
    role                VARCHAR(40)  NOT NULL,
    foot                VARCHAR(6)   NOT NULL,
    dob                 DATE         NOT NULL,
    height_cm           INTEGER,
    shirt_number        INTEGER,
    provenance          VARCHAR(20)  NOT NULL,
    source_name         VARCHAR(120) NOT NULL,
    source_id           BIGINT       REFERENCES import_sources (id) ON DELETE SET NULL,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_players_provenance
        CHECK (provenance IN ('DEMO', 'IMPORTED', 'CALCULATED', 'MODEL_ESTIMATE', 'MANUAL', 'VERIFIED')),
    CONSTRAINT ck_players_position
        CHECK (position IN ('GK', 'CB', 'LB', 'RB', 'DM', 'CM', 'AM', 'LW', 'RW', 'ST')),
    CONSTRAINT ck_players_secondary_position
        CHECK (secondary_position IS NULL OR secondary_position IN ('GK', 'CB', 'LB', 'RB', 'DM', 'CM', 'AM', 'LW', 'RW', 'ST')),
    CONSTRAINT ck_players_foot CHECK (foot IN ('Left', 'Right', 'Both')),
    CONSTRAINT ck_players_role CHECK (role IN (
        'goalkeeper', 'ball-playing-cb', 'aggressive-cb', 'attacking-fb', 'defensive-fb',
        'deep-lying-playmaker', 'ball-winner', 'box-to-box', 'advanced-playmaker',
        'winger', 'inverted-winger', 'target-forward', 'mobile-striker')),
    CONSTRAINT ck_players_height CHECK (height_cm IS NULL OR (height_cm >= 150 AND height_cm <= 230)),
    CONSTRAINT ck_players_shirt_number CHECK (shirt_number IS NULL OR shirt_number BETWEEN 1 AND 99)
);

CREATE INDEX idx_players_team_id ON players (team_id);
CREATE INDEX idx_players_position ON players (position);

CREATE TABLE player_season_stats (
    player_id                 BIGINT PRIMARY KEY REFERENCES players (id) ON DELETE CASCADE,
    appearances               INTEGER NOT NULL,
    minutes                   INTEGER NOT NULL,
    starts                    INTEGER NOT NULL,
    goals                     INTEGER NOT NULL,
    assists                   INTEGER NOT NULL,
    shots                     INTEGER NOT NULL,
    xg                        NUMERIC(6, 2) NOT NULL,
    xa                        NUMERIC(6, 2) NOT NULL,
    passes_attempted          INTEGER NOT NULL,
    passes_completed          INTEGER NOT NULL,
    forward_passes_attempted  INTEGER NOT NULL,
    forward_passes_completed  INTEGER NOT NULL,
    progressive_passes        INTEGER NOT NULL,
    passes_final_third        INTEGER NOT NULL,
    line_breaking_passes      INTEGER NOT NULL,
    carries                   INTEGER NOT NULL,
    progressive_carries       INTEGER NOT NULL,
    carries_final_third       INTEGER NOT NULL,
    dribbles_attempted        INTEGER NOT NULL,
    dribbles_completed        INTEGER NOT NULL,
    touches                   INTEGER NOT NULL,
    turnovers                 INTEGER NOT NULL,
    build_up_receptions       INTEGER NOT NULL,
    build_up_turnovers        INTEGER NOT NULL,
    tackles                   INTEGER NOT NULL,
    interceptions             INTEGER NOT NULL,
    recoveries                INTEGER NOT NULL,
    recoveries_final_third    INTEGER NOT NULL,
    clearances                INTEGER NOT NULL,
    aerials_won               INTEGER NOT NULL,
    aerials_contested         INTEGER NOT NULL,
    provenance                VARCHAR(20)  NOT NULL,
    source_name               VARCHAR(120) NOT NULL,
    created_at                TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at                TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_pss_provenance
        CHECK (provenance IN ('DEMO', 'IMPORTED', 'CALCULATED', 'MODEL_ESTIMATE', 'MANUAL', 'VERIFIED')),
    CONSTRAINT ck_pss_counts CHECK (
        appearances >= 0 AND minutes >= 0 AND starts >= 0 AND starts <= appearances
        AND goals >= 0 AND assists >= 0 AND shots >= 0
        AND passes_completed <= passes_attempted
        AND forward_passes_completed <= forward_passes_attempted
        AND dribbles_completed <= dribbles_attempted
        AND aerials_won <= aerials_contested),
    CONSTRAINT ck_pss_xg CHECK (xg >= 0 AND xa >= 0)
);

-- ----------------------------------------------------------------------------
-- Matches
-- ----------------------------------------------------------------------------
CREATE TABLE matches (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competition_id  BIGINT       NOT NULL REFERENCES competitions (id) ON DELETE RESTRICT,
    season_id       BIGINT       NOT NULL REFERENCES seasons (id) ON DELETE RESTRICT,
    round           INTEGER      NOT NULL,
    kickoff         TIMESTAMPTZ  NOT NULL,
    home_team_id    BIGINT       NOT NULL REFERENCES teams (id) ON DELETE RESTRICT,
    away_team_id    BIGINT       NOT NULL REFERENCES teams (id) ON DELETE RESTRICT,
    home_goals      INTEGER      NOT NULL,
    away_goals      INTEGER      NOT NULL,
    venue           VARCHAR(120) NOT NULL,
    possession_home INTEGER      NOT NULL,
    shots_home      INTEGER      NOT NULL,
    shots_away      INTEGER      NOT NULL,
    provenance      VARCHAR(20)  NOT NULL,
    source_id       BIGINT       REFERENCES import_sources (id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_matches_provenance
        CHECK (provenance IN ('DEMO', 'IMPORTED', 'CALCULATED', 'MODEL_ESTIMATE', 'MANUAL', 'VERIFIED')),
    CONSTRAINT ck_matches_goals CHECK (home_goals >= 0 AND away_goals >= 0),
    CONSTRAINT ck_matches_possession CHECK (possession_home BETWEEN 0 AND 100),
    CONSTRAINT ck_matches_round CHECK (round >= 1),
    CONSTRAINT ck_matches_distinct_teams CHECK (home_team_id <> away_team_id)
);

CREATE INDEX idx_matches_season_id ON matches (season_id);
CREATE INDEX idx_matches_kickoff ON matches (kickoff);
CREATE INDEX idx_matches_home_team_id ON matches (home_team_id);
CREATE INDEX idx_matches_away_team_id ON matches (away_team_id);

-- ----------------------------------------------------------------------------
-- Player match minutes (one row per player per match)
-- ----------------------------------------------------------------------------
CREATE TABLE player_match_minutes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id   BIGINT       NOT NULL REFERENCES matches (id) ON DELETE CASCADE,
    player_id  BIGINT       NOT NULL REFERENCES players (id) ON DELETE CASCADE,
    minutes    INTEGER      NOT NULL,
    starter    BOOLEAN      NOT NULL,
    rating     NUMERIC(3, 1),
    provenance VARCHAR(20)  NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_player_match_minutes_match_player UNIQUE (match_id, player_id),
    CONSTRAINT ck_pmm_provenance
        CHECK (provenance IN ('DEMO', 'IMPORTED', 'CALCULATED', 'MODEL_ESTIMATE', 'MANUAL', 'VERIFIED')),
    CONSTRAINT ck_pmm_minutes CHECK (minutes BETWEEN 1 AND 130),
    CONSTRAINT ck_pmm_rating CHECK (rating IS NULL OR rating BETWEEN 0 AND 10)
);

CREATE INDEX idx_pmm_player_id ON player_match_minutes (player_id);

-- ----------------------------------------------------------------------------
-- Match events
-- ----------------------------------------------------------------------------
CREATE TABLE match_events (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id            BIGINT        NOT NULL REFERENCES matches (id) ON DELETE CASCADE,
    minute              INTEGER       NOT NULL,
    type                VARCHAR(20)   NOT NULL,
    team_id             BIGINT        NOT NULL REFERENCES teams (id) ON DELETE RESTRICT,
    player_id           BIGINT        REFERENCES players (id) ON DELETE SET NULL,
    secondary_player_id BIGINT        REFERENCES players (id) ON DELETE SET NULL,
    x                   NUMERIC(5, 2),
    y                   NUMERIC(5, 2),
    end_x               NUMERIC(5, 2),
    end_y               NUMERIC(5, 2),
    value               NUMERIC(5, 2),
    note                VARCHAR(500),
    provenance          VARCHAR(20)   NOT NULL,
    source_id           BIGINT        REFERENCES import_sources (id) ON DELETE SET NULL,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_events_provenance
        CHECK (provenance IN ('DEMO', 'IMPORTED', 'CALCULATED', 'MODEL_ESTIMATE', 'MANUAL', 'VERIFIED')),
    CONSTRAINT ck_events_type CHECK (type IN (
        'goal', 'own-goal', 'yellow-card', 'red-card', 'substitution',
        'shot', 'chance-created', 'turnover', 'recovery', 'progressive-carry',
        'pass', 'incomplete-pass')),
    CONSTRAINT ck_events_minute CHECK (minute BETWEEN 1 AND 130),
    CONSTRAINT ck_events_x CHECK (x IS NULL OR x BETWEEN 0 AND 100),
    CONSTRAINT ck_events_y CHECK (y IS NULL OR y BETWEEN 0 AND 100),
    CONSTRAINT ck_events_end_x CHECK (end_x IS NULL OR end_x BETWEEN 0 AND 100),
    CONSTRAINT ck_events_end_y CHECK (end_y IS NULL OR end_y BETWEEN 0 AND 100),
    -- two-point events (passes, carries) must carry BOTH end coordinates
    CONSTRAINT ck_events_two_point CHECK (
        type NOT IN ('pass', 'incomplete-pass', 'progressive-carry')
        OR (end_x IS NOT NULL AND end_y IS NOT NULL)),
    CONSTRAINT ck_events_value CHECK (value IS NULL OR value BETWEEN 0 AND 1)
);

CREATE INDEX idx_events_match_minute ON match_events (match_id, minute);
CREATE INDEX idx_events_player_id ON match_events (player_id);
